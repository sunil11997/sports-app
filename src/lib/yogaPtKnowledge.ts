export function getYogaPtGuide(name: string): YogaPtGuide | undefined {
  if (!name) return undefined;
  
  // Direct match
  if (YOGA_PT_KNOWLEDGE_BASE[name]) return YOGA_PT_KNOWLEDGE_BASE[name];
  
  // Partial match by cleaning string
  const cleanName = name.split('(')[0].trim();
  if (YOGA_PT_KNOWLEDGE_BASE[cleanName]) return YOGA_PT_KNOWLEDGE_BASE[cleanName];

  const keyMatch = Object.keys(YOGA_PT_KNOWLEDGE_BASE).find(k => 
    k.toLowerCase().includes(cleanName.toLowerCase()) || 
    cleanName.toLowerCase().includes(k.toLowerCase())
  );

  return keyMatch ? YOGA_PT_KNOWLEDGE_BASE[keyMatch] : undefined;
}
