function guessGender(studentFirst, fullMarathi) {
  if (knownFemales.has(studentFirst)) return 'Female';
  if (studentFirst.endsWith('बाई') || studentFirst.endsWith('कुमारी')) return 'Female';
  return 'Male';
}

function parseDobToIso(dobStr) {
  if (!dobStr || dobStr === '-' || dobStr.trim() === '') return '';
  const parts = dobStr.split('.');
  if (parts.length === 3) {
    const day = parts[0].padStart(2, '0');
    const month = parts[1].padStart(2, '0');
    const year = parts[2];
    return `${year}-${month}-${day}`;
  }
  return dobStr;
}

function calculateAge(isoDob) {
  if (!isoDob) return 10;
  const birth = new Date(isoDob);
  if (isNaN(birth.getTime())) return 10;
  const now = new Date('2026-09-10');
  let age = now.getFullYear() - birth.getFullYear();
  const m = now.getMonth() - birth.getMonth();
  if (m < 0 || (m === 0 && now.getDate() < birth.getDate())) age--;
  return Math.max(3, Math.min(25, age));
}

